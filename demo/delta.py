def native_nanosecond_upgrade_demo() -> None:
    """Check approved new precision independently, outside old paired timings."""
    assert DeltaR(nanoseconds=1000) == DeltaR(microseconds=1)
    assert hash(DeltaR(nanoseconds=1000)) == hash(DeltaR(microseconds=1))
    assert DeltaR(nanoseconds=1) != DeltaR()
    assert DeltaR(microseconds=1, nanoseconds=-1000) == DeltaR()
    start = pd.Timestamp('2024-01-01 00:00:00.123456789')
    assert (start + DeltaR(nanoseconds=1)).value == start.value + 1
    # NumPy date arithmetic keeps its approved datetime result type and rounds
    # only at that final us exit. Retaining 500ns before +1ns changes the answer.
    source = np.datetime64(500, 'ns')
    expected = datetime(1970, 1, 1, microsecond=1)
    assert (DeltaR(nanoseconds=1) + source) == expected
    assert (source + DeltaR(nanoseconds=1)) == expected
    assert (DeltaR(nanoseconds=1) + np.timedelta64(500, 'ns')) == DeltaR(nanoseconds=501)
    assert (np.timedelta64(500, 'ns') + DeltaR(nanoseconds=1)) == DeltaR(nanoseconds=501)
    assert (start + DeltaR(nanosecond=0)).nanosecond == 0
    assert (datetime(2024, 1, 1) + DeltaR(nanoseconds=500)) == datetime(2024, 1, 1)
    assert (datetime(2024, 1, 1) + DeltaR(nanoseconds=1500)) == datetime(2024, 1, 1, microsecond=2)
    print('Native ns upgrade: 12 independent value/field/NumPy/exit checks; not old-version paired timings.')


